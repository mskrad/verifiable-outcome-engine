// Bake the RSA modulus N into the production circuit as a circom constant (PHASE3 step 3).
// Reads the modulus (decimal) from prod_modulus.txt, validates it, and emits:
//   - circuits/prod_n.circom        function PROD_N() returning 32 x 64-bit limbs
//   - build/prod_n_limbs.json       the limbs (for the fixture generator)
//
// Validation guards against transcription errors when pasting the canonical RSA-2048
// Challenge number: exact 2048-bit length, odd, and no small prime factors (a real RSA
// semiprime has none up to large bounds — catches most single-digit typos).
//
// Usage: echo "<decimal N>" > prod_modulus.txt && node bake_n.js
const fs = require("fs");

const raw = fs.readFileSync("prod_modulus.txt", "utf8").replace(/[\s_]/g, "");
if (!/^[0-9]+$/.test(raw)) { console.error("prod_modulus.txt must be a decimal integer"); process.exit(1); }
const N = BigInt(raw);

const bits = N.toString(2).length;
if (bits !== 2048) { console.error(`N must be exactly 2048 bits, got ${bits}`); process.exit(1); }
if ((N & 1n) === 0n) { console.error("N must be odd"); process.exit(1); }

// trial-divide by primes < 100000 (a valid RSA semiprime has no small factors).
function smallFactor(n) {
  if (n % 2n === 0n) return 2n;
  for (let p = 3n; p < 100000n; p += 2n) { if (n % p === 0n) return p; }
  return 0n;
}
const sf = smallFactor(N);
if (sf !== 0n) { console.error(`N has a small factor ${sf} — not a valid RSA modulus (transcription error?)`); process.exit(1); }

const mask64 = (1n << 64n) - 1n;
const limbs = []; let v = N;
for (let i = 0; i < 32; i++) { limbs.push((v & mask64).toString()); v >>= 64n; }

let circ = "pragma circom 2.0.0;\n";
circ += "// AUTO-GENERATED by bake_n.js — RSA modulus baked as a circuit constant (PHASE3 step 3).\n";
circ += "// Source modulus recorded in prod_modulus.txt; rsa_modulus_id = sha256(N) for audit.\n";
circ += "function PROD_N() {\n    var n[32];\n";
for (let i = 0; i < 32; i++) circ += `    n[${i}] = ${limbs[i]};\n`;
circ += "    return n;\n}\n";
fs.writeFileSync("circuits/prod_n.circom", circ);

fs.mkdirSync("build", { recursive: true });
fs.writeFileSync("build/prod_n_limbs.json", JSON.stringify({ N: limbs }, null, 2));

const crypto = require("crypto");
const id = crypto.createHash("sha256").update(be(N, 256)).digest("hex");
function be(x, n) { const b = Buffer.alloc(n); let w = x; for (let i = n - 1; i >= 0; i--) { b[i] = Number(w & 0xffn); w >>= 8n; } return b; }
console.log("OK: N is 2048-bit, odd, no small factors.");
console.log("rsa_modulus_id = sha256(N_be256) =", id);
console.log("wrote circuits/prod_n.circom + build/prod_n_limbs.json");
