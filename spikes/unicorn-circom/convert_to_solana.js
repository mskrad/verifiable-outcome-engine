#!/usr/bin/env node
const fs = require("node:fs");
const path = require("node:path");

const FIELD_P =
  21888242871839275222246405745257275088696311157297823662689037894645226208583n;

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) {
  args.set(process.argv[i], process.argv[i + 1]);
}

const vkPath = args.get("--vk") ?? path.join(process.env.HOME, "Downloads", "vk.json");
const proofPath =
  args.get("--proof") ?? path.join(process.env.HOME, "Downloads", "proof_rs.json");
const publicPath =
  args.get("--public") ?? path.join(process.env.HOME, "Downloads", "public_rs.json");
const outPath =
  args.get("--out") ??
  path.resolve("programs/unicorn-spike/src/generated_ours.rs");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function be32(value) {
  const n = BigInt(value);
  if (n < 0n || n >= FIELD_P) {
    throw new Error(`field element out of range: ${value}`);
  }
  const hex = n.toString(16).padStart(64, "0");
  return Array.from(Buffer.from(hex, "hex"));
}

function g1(point) {
  return [...be32(point[0]), ...be32(point[1])];
}

function g1Neg(point) {
  const y = BigInt(point[1]) % FIELD_P;
  const negY = y === 0n ? 0n : FIELD_P - y;
  return [...be32(point[0]), ...be32(negY)];
}

function g2(point) {
  const x = point[0];
  const y = point[1];
  return [...be32(x[1]), ...be32(x[0]), ...be32(y[1]), ...be32(y[0])];
}

function rustArray(name, bytes, len) {
  if (bytes.length !== len) {
    throw new Error(`${name} expected ${len} bytes, got ${bytes.length}`);
  }
  return `pub const ${name}: [u8; ${len}] = [${bytes.join(", ")}];`;
}

function rustNestedArray(name, rows, rowLen) {
  const body = rows
    .map((row) => {
      if (row.length !== rowLen) {
        throw new Error(`${name} row expected ${rowLen} bytes, got ${row.length}`);
      }
      return `    [${row.join(", ")}],`;
    })
    .join("\n");
  return `pub const ${name}: [[u8; ${rowLen}]; ${rows.length}] = [\n${body}\n];`;
}

const vk = readJson(vkPath);
const proof = readJson(proofPath);
const publicInputs = readJson(publicPath);

if (vk.protocol !== "groth16" || proof.protocol !== "groth16") {
  throw new Error("expected groth16 vk/proof");
}
if (vk.curve !== "bn128") {
  throw new Error(`expected bn128 curve, got ${vk.curve}`);
}
if (Number(vk.nPublic) !== publicInputs.length) {
  throw new Error(`nPublic mismatch: vk=${vk.nPublic}, public=${publicInputs.length}`);
}
if (vk.IC.length !== publicInputs.length + 1) {
  throw new Error(`IC length mismatch: ${vk.IC.length}`);
}

const generated = [
  "// Generated by spikes/unicorn-circom/convert_to_solana.js.",
  "// Source: snarkjs groth16 bn128 vk/proof/public JSON.",
  "",
  rustArray("VK_ALPHA_G1", g1(vk.vk_alpha_1), 64),
  rustArray("VK_BETA_G2", g2(vk.vk_beta_2), 128),
  rustArray("VK_GAMMA_G2", g2(vk.vk_gamma_2), 128),
  rustArray("VK_DELTA_G2", g2(vk.vk_delta_2), 128),
  rustNestedArray("IC", vk.IC.map(g1), 64),
  rustNestedArray("PUBLIC_INPUTS", publicInputs.map(be32), 32),
  rustArray("PROOF_A_NEG", g1Neg(proof.pi_a), 64),
  rustArray("PROOF_B", g2(proof.pi_b), 128),
  rustArray("PROOF_C", g1(proof.pi_c), 64),
  "",
].join("\n");

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, generated);
console.log(`wrote ${outPath}`);
console.log(`public inputs: ${publicInputs.length}, IC: ${vk.IC.length}`);
